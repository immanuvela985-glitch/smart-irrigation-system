"""Streamlit session-state initialization and shared accessors."""

from __future__ import annotations

from datetime import datetime
from typing import Any

import pandas as pd
import streamlit as st

from src.config import (
    DEFAULT_COOLDOWN_SEC,
    DEFAULT_MAX_PUMP_RUNTIME_SEC,
    DEFAULT_MOISTURE_THRESHOLD,
    MODELS_DIR,
    SAMPLE_DATA_PATH,
)
from src.data_processing import load_csv
from src.hardware_interface import DataSource, HardwareManager
from src.model_training import load_model
from src.safety import SafetyConfig
from src.sensor_simulator import write_sample_dataset


def init_state() -> None:
    if st.session_state.get("_initialized"):
        return

    if not SAMPLE_DATA_PATH.exists():
        write_sample_dataset(SAMPLE_DATA_PATH)

    history = load_csv(SAMPLE_DATA_PATH, require_target=False)
    latest = history.iloc[-1].to_dict() if not history.empty else None

    st.session_state.history = history
    st.session_state.latest_reading = latest
    st.session_state.last_update = latest["timestamp"] if latest else None
    st.session_state.read_error = None
    st.session_state.data_source = DataSource.DEMO.value
    st.session_state.serial_port = "COM3"
    st.session_state.wifi_url = "http://192.168.4.1/sensor"
    st.session_state.hardware_configured = False
    st.session_state.hardware = HardwareManager(source=DataSource.DEMO)
    st.session_state.moisture_threshold = DEFAULT_MOISTURE_THRESHOLD
    st.session_state.max_pump_runtime_sec = DEFAULT_MAX_PUMP_RUNTIME_SEC
    st.session_state.cooldown_sec = DEFAULT_COOLDOWN_SEC
    st.session_state.auto_irrigation = False
    st.session_state.training = None
    st.session_state.active_model_name = None
    st.session_state.active_model = None
    st.session_state.model_status = "No trained model is loaded. Predictions currently use a labeled demo rule."
    st.session_state._initialized = True


def safety_config() -> SafetyConfig:
    return SafetyConfig(
        max_runtime_sec=int(st.session_state.max_pump_runtime_sec),
        cooldown_sec=int(st.session_state.cooldown_sec),
    )


def sync_hardware_from_settings() -> HardwareManager:
    hardware: HardwareManager = st.session_state.hardware
    hardware.source = DataSource(st.session_state.data_source)
    hardware.serial_port = st.session_state.serial_port
    hardware.wifi_url = st.session_state.wifi_url
    hardware.hardware_configured = bool(st.session_state.hardware_configured)
    return hardware


def append_reading(reading: dict[str, Any]) -> None:
    history: pd.DataFrame = st.session_state.history
    st.session_state.history = pd.concat([history, pd.DataFrame([reading])], ignore_index=True)
    st.session_state.latest_reading = reading
    st.session_state.last_update = reading.get("timestamp")
    st.session_state.read_error = None


def try_load_named_model(name: str | None) -> None:
    if not name:
        st.session_state.active_model = None
        st.session_state.active_model_name = None
        st.session_state.model_status = "No trained model is loaded. Predictions currently use a labeled demo rule."
        return
    slug = name.lower().replace(" ", "_")
    path = MODELS_DIR / f"{slug}.joblib"
    if not path.exists():
        st.session_state.active_model = None
        st.session_state.model_status = f"No saved file for {name} was found in models/."
        return
    try:
        bundle = load_model(path)
        st.session_state.active_model = bundle
        st.session_state.active_model_name = name
        st.session_state.model_status = f"Loaded {name} from {path.name}."
    except Exception as exc:  # noqa: BLE001
        st.session_state.active_model = None
        st.session_state.model_status = f"Could not load {name}: {exc}"


def saved_model_names() -> list[str]:
    if not MODELS_DIR.exists():
        return []
    names = []
    mapping = {
        "decision_tree.joblib": "Decision Tree",
        "random_forest.joblib": "Random Forest",
        "logistic_regression.joblib": "Logistic Regression",
    }
    for path in sorted(MODELS_DIR.glob("*.joblib")):
        names.append(mapping.get(path.name, path.stem.replace("_", " ").title()))
    return names


def source_banner_text() -> tuple[str, str]:
    source = st.session_state.data_source
    if source == DataSource.DEMO.value:
        return (
            "DEMO SIMULATION",
            "Readings are generated by software. They are not coming from an ESP32.",
        )
    if source == DataSource.SERIAL.value:
        info = st.session_state.hardware.connection_info()
        if info.connected:
            return ("ESP32 SERIAL", "Live USB serial telemetry from a connected ESP32.")
        return ("SERIAL — NOT CONNECTED", info.last_error or info.detail)
    info = st.session_state.hardware.connection_info()
    if info.connected:
        return ("ESP32 WI-FI", "Live HTTP telemetry from a connected ESP32.")
    return ("WI-FI — NOT CONNECTED", info.last_error or info.detail)


def format_timestamp(value: Any) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "Never"
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%d %H:%M:%S")
    ts = pd.to_datetime(value, errors="coerce")
    if pd.isna(ts):
        return "Unknown"
    return ts.strftime("%Y-%m-%d %H:%M:%S")
